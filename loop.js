// for loop
for(let i = 0; i < 5; i++) {
    console.log("The number is " + i);
}


// while loop
let j = 0;
while(j < 5) {
    console.log("The number is " + j);
    j++;
}   



//do while loop
let k = 0;
do {
    console.log("The number is " + k);
    k++;
} while(k < 5);




// for each loop
let numbers = [1, 2, 3, 4, 5];
numbers.forEach(function(number) {
    console.log("The number is " + number);
});